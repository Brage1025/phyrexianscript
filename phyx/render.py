def _indent_of(line: str) -> int:
    width = 0
    for ch in line:
        if ch == " ":
            width += 1
        elif ch == "\t":
            width += 4 - (width % 4)
        else:
            break
    return width


def font_source(local_font: Path | None) -> str:
    """The ``src:`` list for ``@font-face``.

    The TTF's family name is ``Phyrexian`` (full name ``Phyrexian Regular``).
    Prefer an embedded copy of a *validated* local file so the page cannot
    flash Latin fallbacks; then ``local()``, then the CDN and GitHub copies.
    """
    parts: list[str] = []
    if is_font_file(local_font):
        data = base64.b64encode(local_font.read_bytes()).decode("ascii")  # type: ignore[union-attr]
        parts.append(f'url("data:font/ttf;base64,{data}") format("truetype")')
    parts.append(f'local("{FONT_FAMILY}")')
    parts.append(f'local("{FONT_FULL_NAME}")')
    parts.append(f'url("{FONT_CDN}") format("truetype")')
    parts.append(f'url("{FONT_REMOTE}") format("truetype")')
    return ",\n       ".join(parts)


def render_html(source: str, title: str = "", local_font: Path | None = None,
                size: int = 34, indent_unit: int = 4) -> str:
    source = unicodedata.normalize("NFC", source.lstrip("\ufeff"))
    if source.startswith("#!"):
        nl = source.find("\n")
        source = "\n" if nl < 0 else "\n" + source[nl + 1 :]
    lines = [ln.rstrip("\r") for ln in source.split("\n")]
    while lines and lines[-1] == "":
        lines.pop()

    cols: list[str] = []
    for i, line in enumerate(lines, start=1):
        text = line.strip()
        if not text:
            cols.append(f'<div class="col blank" style="--indent:0"><span class="n">{i}</span></div>')
            continue
        indent = _indent_of(line) / indent_unit
        esc = html.escape(text, quote=False)
        cls = "col note" if text.startswith("^rukx") else "col"
        cols.append(
            f'<div class="{cls}" style="--indent:{indent:g}">'
            f'<span class="n">{i}</span>'
            f'<span class="phy">{esc}</span>'
            f'<span class="rom">{esc}</span>'
            f"</div>"
        )

    return _TEMPLATE.format(
        title=html.escape(title or "φyrx"),
        title_html=html.escape(title) if title else "",
        font_family=FONT_FAMILY,
        font_full=FONT_FULL_NAME,
        font_src=font_source(local_font),
        size=size,
        columns="\n".join(cols),
    )
